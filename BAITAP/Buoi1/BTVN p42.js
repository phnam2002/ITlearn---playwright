// Tính tiền hoá đơn đi siêu thị
const applePrice = 25000; // Giá 1kg táo
const appleWeight = 3;    // Số kg táo đã mua

const orangePrice = 30000; // Giá 1kg cam
const orangeWeight = 2;    // Số kg cam đã mua
// Yêu cầu: Hãy dùng Template Literals để in ra câu:
// "Tổng tiền mua hoa quả là: ... VNĐ" (Thay dấu ... bằng phép tính để ra tổng số tiền).
// Gợi ý: Dùng * cho các công thức nhân

console.log(`Tổng tiền mua hoa quả là: ${applePrice * appleWeight + orangePrice * orangeWeight} VNĐ`);
